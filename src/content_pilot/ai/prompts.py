def project_context(project: object) -> str:
    return (
        f"Проект: {project.name}\nОписание: {project.description or 'Не указано'}\n"
        f"Аудитория: {project.audience or 'Не указана'}\nТон общения: {project.tone_of_voice or 'Не указан'}\n"
        f"Язык проекта: {project.language}\n{language_instruction(project.language)}\n"
        f"{russian_quality_instruction(project.language)}\n"
        f"{factual_grounding_instruction()}"
    )


def content_plan_prompt(project: object, start_date: date, end_date: date, posts_count: int, platforms: list[Platform]) -> str:
    return f"""Составь разнообразный контент-план. Верни только запрошенные структурированные данные.
{project_context(project)}
Период: с {start_date.isoformat()} по {end_date.isoformat()}. Количество: {posts_count}.
Платформы: {', '.join(platform.value for platform in platforms)}.
Избегай повторяющихся тем и плана из одной категории. Не предлагай generic-темы вроде «Почему AI важен для современных разработчиков».
Предпочитай темы, которые можно раскрыть через конкретный опыт из контекста, архитектурное решение, инструмент, ошибку, сравнение или практический вывод. Не пиши готовые посты."""


